export const inRange = (E, P, R) => E >= 10 && E <= 60 && P >= -20 && P <= 60 && R >= -0.5 * P - 50 && R <= -0.5 * P + 10;
// the measured leverage at (E, P, R): { elev, plane, rot }, each by muscle name, mm
export function measured(E, P, R) {
  const out = {};
  for (const k of ['elev', 'plane', 'rot']) { const v = NAMES.map(() => 0); for (const t of TERMS[k]) { const x = E ** t[8] * P ** t[9] * R ** t[10]; for (let i = 0; i < 8; i++) v[i] += t[i] * x; } out[k] = Object.fromEntries(NAMES.map((n, i) => [n, v[i]])); }
  return out;
}
